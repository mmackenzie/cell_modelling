for i = 1:numel(field_names)
    field = field_names{i};
    
    % Only process fields that start with 'CMD' and contain 'Cell'
    if contains(field, 'CMD') && contains(field, 'Cell') && ~contains(field, 'Temp')
        voltage_tt = DATA.(field);  % A timetable

        % Extract start and end voltages for all columns (cells)
        start_voltages = voltage_tt{1, :} / 1000;
        end_voltages = voltage_tt{end, :} / 1000;

        % Convert to SOC using interpolation
        start_soc = interp1(OCV_ref, SOC_ref, start_voltages, 'linear', 'extrap');
        end_soc = interp1(OCV_ref, SOC_ref, end_voltages, 'linear', 'extrap');

        % Store results
        start_soc_all = [start_soc_all, start_soc];
        end_soc_all = [end_soc_all, end_soc];
        delta_soc = end_soc - start_soc;
        delta_soc_all = [delta_soc_all, delta_soc];

        fprintf("%s: %.1f, %.1f, %.1f\n", field, delta_soc(1)*100, delta_soc(2)*100, delta_soc(3)*100);
    end
end

